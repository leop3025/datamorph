import type { Dataset } from "@/lib/data/types";
import { getStepDef } from "./registry";
import { py, pyList } from "./literals";

interface Section {
  title: string;
  code: string[];
  /** DataFrame to preview after this cell in notebooks */
  preview?: string;
}

const varName = (ds: Dataset) => `df_${ds.table}`;

function loadLine(ds: Dataset, v: string): string[] {
  const { fileName, format, url, sample } = ds.source;
  const path = py(url && !sample ? url : fileName);
  const dates = ds.source.dateColumns.length ? `, parse_dates=${pyList(ds.source.dateColumns)}` : "";
  const note = sample
    ? [`# Sample dataset: download it from the Datamorph app (/samples/${fileName}) and save it next to this file.`]
    : url
      ? []
      : [`# Put ${fileName} in the same folder as this file.`];
  const ext = fileName.toLowerCase().split(".").pop();
  const reader: Record<string, string> = {
    csv: `pd.read_csv(${path}${ext === "tsv" ? ', sep="\\t"' : ""}${dates})`,
    json: `pd.read_json(${path}${ext === "ndjson" || ext === "jsonl" ? ", lines=True" : ""})`,
    parquet: `pd.read_parquet(${path})`,
    excel: `pd.read_excel(${path})`,
  };
  return [...note, `${v} = ${reader[format]}`];
}

/** Datasets this one depends on through joins (recursively), in load order. */
function dependencies(ds: Dataset, all: Dataset[], seen = new Set<string>()): Dataset[] {
  const out: Dataset[] = [];
  for (const s of ds.steps) {
    if (!s.enabled || s.type !== "join" || seen.has(s.params.right)) continue;
    const dep = all.find((d) => d.id === s.params.right);
    if (!dep || dep.id === ds.id) continue;
    seen.add(dep.id);
    out.push(...dependencies(dep, all, seen), dep);
  }
  return out;
}

function stepSections(ds: Dataset, v: string, all: Dataset[]): Section[] {
  return ds.steps.flatMap((step, i) => {
    if (!step.enabled) return [];
    const def = getStepDef(step.type);
    const title = `Step ${i + 1}: ${def.summary(step.params, all)}`;
    if (ds.stepErrors[step.id]) return [{ title, code: [`# Skipped: this step failed in Datamorph (${ds.stepErrors[step.id]})`] }];
    const code = def.pandas(step.params, { df: v, cols: ds.schemas[i] ?? ds.columns, dfName: (id) => {
      const d = all.find((x) => x.id === id);
      return d ? varName(d) : "df_missing";
    }, datasets: all });
    return [{ title, code, preview: v }];
  });
}

type Loader = (ds: Dataset, v: string) => string[];

/** SQL query steps export as duckdb calls, so the script needs the duckdb package. */
export function usesSql(ds: Dataset, deps: Dataset[] = []): boolean {
  return [ds, ...deps].some((d) => d.steps.some((s) => s.enabled && s.type === "sql"));
}

function buildSections(ds: Dataset, all: Dataset[], load: Loader = loadLine): Section[] {
  const deps = dependencies(ds, all);
  const setup = ["import numpy as np", "import pandas as pd"];
  if (usesSql(ds, deps)) setup.unshift("import duckdb  # pip install duckdb");
  const sections: Section[] = [{ title: "Setup", code: setup }];
  for (const dep of deps) {
    const v = varName(dep);
    sections.push({ title: `Load ${dep.name} (used in a join)`, code: load(dep, v) });
    sections.push(...stepSections(dep, v, all).map((s) => ({ ...s, title: `${dep.name}: ${s.title}` })));
  }
  sections.push({ title: `Load ${ds.name}`, code: load(ds, "df") });
  sections.push(...stepSections(ds, "df", all));
  return sections;
}

export function generatePython(ds: Dataset, all: Dataset[]): string {
  const header = [
    `# ${ds.name}: cleaning & transformation recipe`,
    "# Generated by Datamorph. Every step below mirrors a step in the app.",
    "",
  ];
  const body = buildSections(ds, all).flatMap((s) => [`# --- ${s.title}`, ...s.code, ""]);
  const footer = [
    "# --- Result",
    `print(df.shape)`,
    `print(df.head())`,
    `df.to_csv(${py(`${ds.table}_clean.csv`)}, index=False)`,
    "",
  ];
  return [...header, ...body, ...footer].join("\n");
}

/**
 * The same script, but reading each source table from a CSV exported by DuckDB and printing a
 * JSON summary, so Datamorph can run it in Pyodide and compare it with its own result.
 */
export function generateVerificationScript(ds: Dataset, all: Dataset[], pathFor: (d: Dataset) => string): string {
  const load: Loader = (d, v) => [
    `${v} = pd.read_csv(${py(pathFor(d))}${d.source.dateColumns.length ? `, parse_dates=${pyList(d.source.dateColumns)}` : ""})`,
  ];
  const body = buildSections(ds, all, load).flatMap((s) => s.code);
  return [
    ...body,
    "import json as _json",
    "_num = df.select_dtypes(include=[np.number, 'bool'])",
    "_json.dumps({'rows': int(df.shape[0]), 'columns': [str(c) for c in df.columns],",
    "             'sums': {str(c): (None if pd.isna(v) else float(v)) for c, v in _num.astype(float).sum().items()}})",
  ].join("\n");
}

export function generateNotebook(ds: Dataset, all: Dataset[]): string {
  let id = 0;
  const lines = (text: string[]) => text.map((l, i) => (i < text.length - 1 ? `${l}\n` : l));
  const md = (text: string[]) => ({ cell_type: "markdown", id: `c${id++}`, metadata: {}, source: lines(text) });
  const code = (text: string[]) => ({
    cell_type: "code",
    id: `c${id++}`,
    metadata: {},
    execution_count: null,
    outputs: [],
    source: lines(text),
  });

  const cells: object[] = [
    md([`# ${ds.name}: cleaning & transformation`, "", "Generated by **Datamorph**. Each cell reproduces one step of the recipe built in the app."]),
  ];
  for (const s of buildSections(ds, all)) {
    cells.push(md([`### ${s.title}`]));
    cells.push(code(s.preview ? [...s.code, `${s.preview}.head()`] : s.code));
  }
  cells.push(md(["### Result"]));
  cells.push(code(["print(df.shape)", "df.describe(include=\"all\").T"]));

  return JSON.stringify(
    {
      cells,
      metadata: {
        kernelspec: { display_name: "Python 3", language: "python", name: "python3" },
        language_info: { name: "python" },
      },
      nbformat: 4,
      nbformat_minor: 5,
    },
    null,
    1,
  );
}
